-- V2: password reset tokens.
--
-- Same shape as refresh_tokens: random raw token in the email link, SHA-256
-- of it in the row. Single-use: once used_at is set the row is permanently
-- spent. Expired/used rows are purged by a scheduled sweep (see
-- PasswordResetTokenCleanup).

CREATE TABLE password_reset_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users (id),
    token_hash    VARCHAR(64) NOT NULL,
    expires_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at       TIMESTAMP(6) WITH TIME ZONE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    requested_ip  VARCHAR(64),
    user_agent    VARCHAR(512)
);

CREATE UNIQUE INDEX idx_pwd_reset_token_hash ON password_reset_tokens (token_hash);
CREATE        INDEX idx_pwd_reset_user_id    ON password_reset_tokens (user_id);
