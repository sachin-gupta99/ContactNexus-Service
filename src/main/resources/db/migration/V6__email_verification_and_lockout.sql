-- V6: email verification and per-account login lockout.

-- Accounts created before verification existed are already in use, so they
-- are treated as verified rather than locked out on their next sign-in.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE users SET email_verified = TRUE;

ALTER TABLE users ADD COLUMN failed_login_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN locked_until TIMESTAMP(6) WITH TIME ZONE;

-- Same shape as password_reset_tokens: the raw token only ever exists in the
-- emailed link; the row stores its SHA-256.
CREATE TABLE email_verification_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP(6) WITH TIME ZONE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX idx_email_verif_token_hash ON email_verification_tokens (token_hash);
CREATE        INDEX idx_email_verif_user_id    ON email_verification_tokens (user_id);
