-- V7: contact tags (groups) and uploaded contact photos.

-- A tag exists only while some contact uses it; names are unique per owner,
-- ignoring case ("Work" and "work" are the same tag).
CREATE TABLE tags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT       NOT NULL,
    name        VARCHAR(30)  NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX uq_tags_owner_lower_name ON tags (owner_id, lower(name));

-- ON DELETE CASCADE on both sides: deleting a contact (including the bulk
-- delete on account removal) or a tag removes the link rows with it.
CREATE TABLE contact_tags (
    contact_id  BIGINT NOT NULL REFERENCES contacts (id) ON DELETE CASCADE,
    tag_id      BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (contact_id, tag_id)
);

CREATE INDEX idx_contact_tags_tag_id ON contact_tags (tag_id);

-- S3 key of an uploaded photo (same bucket and prefix as user avatars). When
-- set it wins over image_url, and the API returns a presigned URL instead.
ALTER TABLE contacts ADD COLUMN image_key VARCHAR(255);
