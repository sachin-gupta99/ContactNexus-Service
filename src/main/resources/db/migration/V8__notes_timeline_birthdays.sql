-- V8: notes, an interaction timeline, birthdays and birthday reminders.

ALTER TABLE contacts ADD COLUMN notes VARCHAR(10000);

-- Kept in step with the newest interaction, so lists can show and sort by it
-- without a join.
ALTER TABLE contacts ADD COLUMN last_contacted_at TIMESTAMP(6) WITH TIME ZONE;

-- Month and day are required together; the year is optional ("25 Dec").
ALTER TABLE contacts ADD COLUMN birthday_month INT;
ALTER TABLE contacts ADD COLUMN birthday_day INT;
ALTER TABLE contacts ADD COLUMN birthday_year INT;
ALTER TABLE contacts ADD CONSTRAINT chk_contacts_birthday CHECK (
    (birthday_month IS NULL AND birthday_day IS NULL AND birthday_year IS NULL)
    OR (birthday_month BETWEEN 1 AND 12 AND birthday_day BETWEEN 1 AND 31)
);
CREATE INDEX idx_contacts_birthday ON contacts (birthday_month, birthday_day)
    WHERE birthday_month IS NOT NULL;

CREATE TABLE interactions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL,
    contact_id   BIGINT       NOT NULL REFERENCES contacts (id) ON DELETE CASCADE,
    type         VARCHAR(20)  NOT NULL,
    note         VARCHAR(1000),
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_interactions_contact_time ON interactions (contact_id, occurred_at DESC);

ALTER TABLE users ADD COLUMN birthday_reminders BOOLEAN NOT NULL DEFAULT TRUE;

-- One row per reminder sent, so the in-app schedule and the external trigger
-- can both run without anyone getting the same email twice.
CREATE TABLE reminder_log (
    contact_id  BIGINT      NOT NULL REFERENCES contacts (id) ON DELETE CASCADE,
    kind        VARCHAR(20) NOT NULL,
    for_date    DATE        NOT NULL,
    sent_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (contact_id, kind, for_date)
);
