-- V1: Initial schema baseline.
--
-- Describes the schema Hibernate's `ddl-auto: update` produced on main before
-- Flyway was introduced. Deployed environments (prod Neon, any dev DB that
-- already booted the app) will NOT re-run this: `baseline-on-migrate=true`
-- in application.yml tells Flyway to stamp the existing DB as being at V1 and
-- skip execution. Fresh databases (local Docker, Testcontainers, a brand new
-- Neon branch) run it in full so the schema matches current entities before
-- Hibernate `validate` kicks in.
--
-- Everything from V2 onwards is the real changelog: never edit this file
-- again once it has been applied anywhere.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    name          VARCHAR(255) NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE profiles (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL UNIQUE REFERENCES users (id),
    work            VARCHAR(255),
    phone           VARCHAR(255),
    street          VARCHAR(255),
    area            VARCHAR(255),
    city            VARCHAR(255),
    state           VARCHAR(255),
    pincode         VARCHAR(255),
    github          VARCHAR(255),
    linkedin        VARCHAR(255),
    instagram       VARCHAR(255),
    likes           VARCHAR(255),
    movie           VARCHAR(255),
    interests       VARCHAR(255),
    bio_heading     VARCHAR(255),
    bio_description VARCHAR(1000),
    image_url       VARCHAR(255)
);

CREATE TABLE contacts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT       NOT NULL,
    first_name    VARCHAR(255) NOT NULL,
    last_name     VARCHAR(255),
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(255),
    bio           VARCHAR(1000),
    image_url     VARCHAR(255),
    street        VARCHAR(255),
    city          VARCHAR(255),
    state         VARCHAR(255),
    country       VARCHAR(255),
    zip_code      VARCHAR(255),
    github_url    VARCHAR(255),
    linkedin_url  VARCHAR(255),
    instagram_url VARCHAR(255),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE refresh_tokens (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id),
    token_hash       VARCHAR(64) NOT NULL,
    family_id        UUID NOT NULL,
    expires_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at       TIMESTAMP(6) WITH TIME ZONE,
    replaced_by_hash VARCHAR(64),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_agent       VARCHAR(512),
    ip_address       VARCHAR(64)
);

CREATE UNIQUE INDEX idx_refresh_token_hash      ON refresh_tokens (token_hash);
CREATE        INDEX idx_refresh_token_user_id   ON refresh_tokens (user_id);
CREATE        INDEX idx_refresh_token_family_id ON refresh_tokens (family_id);
